"""Generate RESULTS.md, EXPERIMENT_REPORT.md, the HTML report and resume_evidence/metrics.json.

All numbers are read from saved JSON records (reports/runs, reports/experiments,
reports/baselines-*.json). Hand-written interpretation lives in
``reports/experiments/<name>/note.md`` and is included verbatim.
"""

from __future__ import annotations

import base64
import html
import json
from pathlib import Path
from typing import Any

from morrowglass.experiments.registry import ALL
from morrowglass.repro import REPO_ROOT, git_provenance, now_iso, read_json, write_json, write_verified

REPORTS = REPO_ROOT / "reports"
DOCS = REPO_ROOT / "docs"


def _f(x: Any, d: int = 4) -> str:
    return "—" if x is None else (f"{x:.{d}f}" if isinstance(x, float) else str(x))


def _ci(ci: list[float] | None) -> str:
    return "—" if not ci else f"[{ci[0]:.3f}, {ci[1]:.3f}]"


def _load_results() -> dict[str, dict[str, Any]]:
    out = {}
    for n in [*ALL, *(f"{a}-extended" for a in ALL), "lora"]:
        p = REPORTS / "experiments" / n / "result.json"
        if p.exists():
            out[n] = read_json(p)
    return out


def _baseline_table(bl: dict[str, Any]) -> list[str]:
    lines = ["| tokenizer | model | val bits/byte | 95% CI |", "|---|---|---|---|"]
    for r in bl["results"]:
        lines.append(f"| {r['tokenizer']} | {r['model']} | {_f(r['val']['bits_per_byte'])} | {_ci(r['val'].get('bits_per_byte_ci95'))} |")
    return lines


def _run_table(rows: list[dict[str, Any]]) -> list[str]:
    lines = ["| run id | status | params | tokens | val bits/byte | 95% CI | ECE | wall (s) | commit |",
             "|---|---|---|---|---|---|---|---|---|"]
    for r in rows:
        lines.append(f"| `{r['run_id']}` | {r['status']} | {r['params']:,} | {r['tokens_seen']:,} | {_f(r['val_bpb'])} | "
                     f"{_ci(r['val_bpb_ci95'])} | {_f(r['ece'], 3)} | {r['wall_time_s']} | `{r['git_commit'][:8]}`"
                     f"{'*' if r['git_dirty'] else ''} |")
    return lines


def _paired_lines() -> list[str]:
    """Short summary of reports/paired/summary.json (post-hoc paired re-analysis), if measured."""
    pp = REPORTS / "paired" / "summary.json"
    if not pp.exists():
        return []
    s = read_json(pp)
    blk = str(s["protocol"]["primary_block_bytes"])
    L = ["## Paired re-analysis vs the best n-gram (post-hoc)", "",
         f"Registered {s['registered']} after the scratch verdict was known (`EVALUATIONS['paired-baseline']`); it "
         "does not change that verdict. Same validation bytes, contiguous "
         f"{int(blk) // 1024} KiB blocks, same resampled blocks for both models. Verdict for the flagship: "
         f"**{s['verdict']}**. Full tables: [PAIRED_RESULTS.md](PAIRED_RESULTS.md).", "",
         "| run | bpb(run) - bpb(n-gram) | paired 95% interval | lower in every play |", "|---|---:|---|---|"]
    for rid, r in s["runs"].items():
        p = r["paired"][blk]
        L.append(f"| `{rid}` | {p['difference']:+.4f} | [{p['ci95'][0]:+.4f}, {p['ci95'][1]:+.4f}] | "
                 f"{'yes' if all(x['difference'] < 0 for x in r['plays']) else 'no'} |")
    return L + [""]


def build_results_md(results: dict[str, dict[str, Any]]) -> str:
    bl_path = REPORTS / "baselines-shakespeare.json"
    L = ["# Results", "",
         "> Generated by `morrowglass report` from saved run records. Do not edit by hand.",
         f"> Generated {now_iso()} at commit `{git_provenance()['commit'][:8]}`. `*` after a commit means the",
         "> working tree had uncommitted changes when the run started.", ""]
    if bl_path.exists():
        bl = read_json(bl_path)
        L += ["## Baselines (validation split, Shakespeare held-out plays)", "",
              f"Dataset hash `{bl['dataset_hash'][:12]}`. Best on validation: **{bl['best']['model']} ({bl['best']['tokenizer']})**, "
              f"{bl['best_val_bpb']:.4f} bits/byte.", ""] + _baseline_table(bl) + [""]
    for n, r in results.items():
        L += [f"## {r['title']}", "", f"Experiment `{n}` · verdict **{r['verdict']}** · {r.get('verdict_detail', '')}", ""]
        if r.get("table"):
            L += _run_table(r["table"]) + [""]
        if r.get("observations"):
            obs = {k: v for k, v in r["observations"].items() if k != "calibration"}
            L += ["<details><summary>observations (raw)</summary>", "", "```json", json.dumps(obs, indent=1, default=str), "```",
                  "</details>", ""]
    L += _paired_lines()
    tl = REPORTS / "test_access_log.jsonl"
    L += ["## Locked test split", ""]
    if tl.exists():
        for ln in tl.read_text().splitlines():
            e = json.loads(ln)
            L.append(f"- {e['time']} opened for {len(e['runs'])} run(s){' + baseline' if e['baseline'] else ''} at `{e['git'][:8]}`: {e['reason']}")
        L.append("")
        for p in sorted((REPORTS / "runs").glob("*/test_eval.json")):
            t = read_json(p)
            for split, v in t["results"].items():
                if "bits_per_byte" in v:
                    L.append(f"- `{t['run_id']}` {split}: {v['bits_per_byte']:.4f} bits/byte {_ci(v.get('bits_per_byte_ci95'))}")
                else:
                    L.append(f"- `{t['run_id']}` {split}: accuracy {v['accuracy']:.4f} (n={v['n']})")
        btp = REPORTS / "baselines-shakespeare-test.json"
        if btp.exists():
            b = read_json(btp)
            L.append(f"- baseline {b['model']['model']} ({b['model']['tokenizer']}) test: {b['test']['bits_per_byte']:.4f} bits/byte "
                     f"{_ci(b['test'].get('bits_per_byte_ci95'))}")
    else:
        L.append("The test split has not been opened.")
    return "\n".join(L) + "\n"


def build_report_md(results: dict[str, dict[str, Any]]) -> str:
    L = ["# Experiment report", "",
         "> Generated by `morrowglass report`. Hypotheses and criteria come from `experiments/registry.py` (written before",
         "> the runs); verdicts from `experiments/analyze.py`; notes from `reports/experiments/<name>/note.md`.", "",
         "Exact numbers with run ids: [RESULTS.md](RESULTS.md).", ""]
    for n, r in results.items():
        L += [f"## {r['title']}", "", f"**Verdict: {r['verdict']}.** {r.get('verdict_detail', '')}", "",
              f"- **Hypothesis.** {r['hypothesis']}", f"- **Criterion (pre-registered).** {r['criterion']}",
              f"- **Runs.** {', '.join(f'`{a}`' for a in r['arms'])}",
              "- **Caveats.** " + " ".join(r["caveats"]), ""]
        for p in r.get("plots", []):
            L.append(f"![{n} {p}](../reports/experiments/{n}/{p})")
        L.append("")
        if r.get("researcher_note"):
            L += [r["researcher_note"].strip(), ""]
        else:
            L += ["_Researcher note pending._", ""]
        if n == "scratch":
            L += [ln.replace("## ", "### ", 1) if ln.startswith("## ") else ln for ln in _paired_lines()]
    return "\n".join(L) + "\n"


def build_html(md_results: str, results: dict[str, dict[str, Any]]) -> str:
    parts = ["<!doctype html><html lang=en><meta charset=utf-8><meta name=viewport content='width=device-width,initial-scale=1'>",
             "<title>Morrowglass experiment report</title><style>body{font:15px/1.5 -apple-system,Segoe UI,sans-serif;max-width:960px;"
             "margin:2rem auto;padding:0 16px;color:#1b1d21;background:#fff}pre{background:#f4f3ef;padding:8px;overflow:auto}"
             "img{max-width:100%;border:1px solid #ddd}code{font-family:ui-monospace,Menlo,monospace;font-size:13px}"
             ".v{font-weight:700}</style><h1>Morrowglass Model Foundry: experiment report</h1>",
             f"<p>Generated {html.escape(now_iso())} at commit <code>{git_provenance()['commit'][:8]}</code>. "
             "Every figure below is computed from saved run records; plots are embedded.</p>"]
    for n, r in results.items():
        parts.append(f"<h2>{html.escape(r['title'])}</h2><p class=v>Verdict: {html.escape(r['verdict'])}</p>"
                     f"<p>{html.escape(r.get('verdict_detail') or '')}</p><p><b>Hypothesis.</b> {html.escape(r['hypothesis'])}</p>"
                     f"<p><b>Criterion.</b> {html.escape(r['criterion'])}</p>")
        for p in r.get("plots", []):
            img = REPORTS / "experiments" / n / p
            if img.exists():
                b64 = base64.b64encode(img.read_bytes()).decode()
                parts.append(f"<img alt='{html.escape(n)} {html.escape(p)}' src='data:image/png;base64,{b64}'>")
        if r.get("researcher_note"):
            parts.append(f"<pre>{html.escape(r['researcher_note'])}</pre>")
    parts.append(f"<h2>All numbers</h2><pre>{html.escape(md_results)}</pre></html>")
    return "".join(parts)


def build_metrics_json(results: dict[str, dict[str, Any]]) -> dict[str, Any]:
    """Resume-evidence claims. Only entries computed from records are 'verified'."""
    claims: list[dict[str, Any]] = []
    ds = REPO_ROOT / "data" / "manifests" / "shakespeare.json"
    dsv = None
    if ds.exists():
        from morrowglass.repro import sha256_bytes

        m = read_json(ds)
        dsv = sha256_bytes("|".join(f"{k}:{v['sha256']}" for k, v in sorted(m["files"].items())).encode())[:16]

    def add(claim: str, value: Any, unit: str, src: str, cmd: str, status: str = "verified") -> None:
        claims.append({"claim": claim, "value": value, "unit": unit, "run_id_or_source": src,
                       "dataset_version": dsv, "reproduction_command": cmd, "status": status})

    s = results.get("scratch")
    if s and s["verdict"] != "pending":
        o = s["observations"]
        add("Scratch byte-level Transformer validation bits-per-byte on 3 held-out Shakespeare plays",
            round(o["transformer_val_bpb"], 4), "bits/byte", s["arms"][0], "make reproduce-scratch")
        add("Best count-based baseline (interpolated Kneser-Ney, order chosen on validation) validation bits-per-byte",
            round(o["baseline_val_bpb"], 4), "bits/byte", "reports/baselines-shakespeare.json", "uv run morrowglass baselines")
        add("Transformer parameter count", s["table"][0]["params"], "parameters", s["arms"][0], "make reproduce-scratch")
    se = results.get("scratch-extended")
    if se and se["verdict"] != "pending":
        o = se["observations"]
        add("Scratch byte-level Transformer, extended budget (10k steps), validation bits-per-byte (95% CI "
            f"{_ci(o['transformer_val_bpb_ci95'])}) vs best n-gram {o['baseline_val_bpb']:.4f}",
            round(o["transformer_val_bpb"], 4), "bits/byte", se["arms"][0],
            "uv run morrowglass run scratch --profile extended --approved")
    t = results.get("tokenization")
    if t and t["verdict"] != "pending":
        o = t["observations"]
        add("BPE-1024 vs byte tokenization val bits-per-byte at equal steps (bpe, byte)",
            [round(o["bpe_val_bpb"], 4), round(o["byte_val_bpb"], 4)], "bits/byte", ",".join(t["arms"]),
            "uv run morrowglass run tokenization")
    opt = results.get("optimization")
    if opt and opt["verdict"] != "pending":
        add("Optimization ablation: configs x seeds executed", len(opt["arms"]), "runs", "reports/experiments/optimization/result.json",
            "uv run morrowglass run optimization")
    btp = REPORTS / "baselines-shakespeare-test.json"
    for p in sorted((REPORTS / "runs").glob("lm-*/test_eval.json")):
        te = read_json(p)
        if "test" in te["results"]:
            v = te["results"]["test"]
            add(f"Locked-test bits-per-byte of {te['run_id']} (95% CI {_ci(v['bits_per_byte_ci95'])})",
                round(v["bits_per_byte"], 4), "bits/byte", te["run_id"], "uv run morrowglass final-test (logged access)")
    if btp.exists():
        b = read_json(btp)
        add(f"Locked-test bits-per-byte of the best n-gram baseline {b['model']['model']} ({b['model']['tokenizer']}) "
            f"(95% CI {_ci(b['test']['bits_per_byte_ci95'])})", round(b["test"]["bits_per_byte"], 4), "bits/byte",
            "reports/baselines-shakespeare-test.json", "uv run morrowglass final-test (logged access)")
    sp = results.get("digitsum-scratchpad")
    if sp and sp["verdict"] != "pending":
        acc = sp["observations"]["accuracy"]
        add("Digit-sum scratchpad: in-distribution final-answer accuracy, all 4 runs (min)",
            round(min(v["val_iid_acc"] for v in acc.values()), 4), "accuracy", ",".join(sp["arms"]),
            "uv run morrowglass run digitsum-scratchpad")
    pp = REPORTS / "paired" / "summary.json"
    if pp.exists():
        ps = read_json(pp)
        pf = ps["runs"][ps["primary_run"]]["paired"][str(ps["protocol"]["primary_block_bytes"])]
        add("Flagship minus best n-gram, paired over 8 KiB validation blocks (post-hoc; 95% interval)",
            [round(pf["difference"], 4), [round(pf["ci95"][0], 4), round(pf["ci95"][1], 4)]], "bits/byte",
            "reports/paired/summary.json", "make paired")
    ss = results.get("scratch-seeds")
    if ss and ss["verdict"] not in ("pending", "n/a"):
        o = ss["observations"]
        add("Flagship recipe validation bits-per-byte across seeds 0-2 (mean, sd)",
            [round(o["seed_mean"], 4), round(o["seed_stdev"], 4)], "bits/byte",
            "reports/experiments/scratch-seeds/result.json", "uv run morrowglass run scratch-seeds")
    dseeds = results.get("digitsum-scratchpad-seeds")
    if dseeds and dseeds["verdict"] not in ("pending", "n/a"):
        o = dseeds["observations"]
        add("Seeds (of 5) in which position augmentation transfers to 12-16-term sums (> 3 SE over plain)",
            o["transfer_count"], "seeds", "reports/experiments/digitsum-scratchpad-seeds/result.json",
            "uv run morrowglass run digitsum-scratchpad-seeds")
    tests_file = REPORTS / "test_summary.json"
    if tests_file.exists():
        ts = read_json(tests_file)
        add("Automated tests passing (pytest, CPU)", ts["passed"], "tests", "reports/test_summary.json", "make test")
    lo = results.get("lora")
    if lo and lo["verdict"] != "pending":
        o = lo["observations"]
        add("distilgpt2 validation bits-per-byte, frozen vs LoRA-adapted (r=8, 300 steps)",
            [round(o["frozen_val"]["bits_per_byte"], 4), round(o["lora_val"]["bits_per_byte"], 4)], "bits/byte",
            "reports/lora/distilgpt2-s0.json", "uv run morrowglass lora --approved")
    else:
        add("Pretrained LoRA adaptation compared with frozen baseline", None, "—", "not executed",
            "requires owner approval for a model download", status="planned")
    out = {"generated": now_iso(), "git": git_provenance()["commit"],
           "policy": "Only status=verified claims may be used as resume achievements.", "claims": claims}
    write_json(REPO_ROOT / "resume_evidence" / "metrics.json", out)
    return out


def build_report() -> str:
    results = _load_results()
    md_results = build_results_md(results)
    write_verified(DOCS / "RESULTS.md", md_results.encode())
    write_verified(DOCS / "EXPERIMENT_REPORT.md", build_report_md(results).encode())
    write_verified(REPORTS / "experiment_report.html", build_html(md_results, results).encode())
    build_metrics_json(results)
    return f"wrote docs/RESULTS.md, docs/EXPERIMENT_REPORT.md, reports/experiment_report.html, resume_evidence/metrics.json ({len(results)} experiments)"


__all__ = ["build_report"]
