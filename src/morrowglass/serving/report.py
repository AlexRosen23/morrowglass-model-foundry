"""docs/SERVING_RESULTS.md, generated from the saved serving/eval records (never typed by hand).

    uv run morrowglass serving-report
"""

from __future__ import annotations

from pathlib import Path
from typing import Any

from morrowglass.repro import REPO_ROOT, read_json

OUT = REPO_ROOT / "docs" / "SERVING_RESULTS.md"


def _load(sub: str) -> dict[str, Any]:
    d = REPO_ROOT / "reports" / sub
    return {p.stem: read_json(p) for p in sorted(d.glob("*.json"))} if d.exists() else {}


def build_serving_report(out: Path = OUT) -> str:
    from morrowglass.experiments.registry import EVALUATIONS

    L: list[str] = ["# Serving and standard-harness results (generated)", "",
                    "Generated by `uv run morrowglass serving-report` from `reports/serving/`, `reports/lm_eval/` and "
                    "`reports/hf_export/`. Do not edit by hand. Each study was registered in "
                    "`src/morrowglass/experiments/registry.py` (`EVALUATIONS`) before it ran.", ""]
    kv = _load("serving/kv-cache")
    ev = EVALUATIONS["kv-cache"]
    L += [f"## {ev.title}", "", f"**Hypothesis (registered {ev.registered}).** {ev.hypothesis}", "",
          f"**Criterion.** {ev.criterion}", ""]
    for rid, k in kv.items():
        L += [f"### `{rid}`: **{k['verdict']}**", "",
              f"`{k['command']}` at commit `{k['git']['commit'][:12]}`{' (dirty)' if k['git']['dirty'] else ''}, "
              f"{k['measured']}, {k['hardware']['chip']}, torch {k['hardware']['torch']}, {k['threads']} threads.", "",
              "| device | prompt tokens | tokens/s, no cache | tokens/s, KV cache | speed-up | TTFT ms (cache) | "
              "decode ms/token median (cache) | p90 |", "|---|---|---|---|---|---|---|---|"]
        for dev in ("cpu", "mps"):
            for n in k["protocol"]["prompt_tokens"]:
                rows = [r for r in k["rows"] if r["device"] == dev and r["prompt_tokens"] == n]
                if len(rows) != 2:
                    continue
                off, on = sorted(rows, key=lambda r: r["kv_cache"])
                L.append(f"| {dev} | {n} | {off['tokens_per_s']} | {on['tokens_per_s']} | "
                         f"{on['tokens_per_s'] / off['tokens_per_s']:.2f}x | {on['ttft_ms']} | "
                         f"{on['decode_ms_per_token']} | {on['p90_decode_ms_per_token']} |")
        eq = k["equivalence_cpu"]
        L += ["", "Equivalence on CPU (real checkpoint, greedy, 64 new tokens): " + "; ".join(
            f"{e['prompt_tokens']}-token prompt: same tokens {e['same_tokens']}, max |Δlogit| "
            f"{e['max_abs_logit_diff']:.1e}" for e in eq) + ".", ""]
    q = _load("serving/int8")
    ev = EVALUATIONS["int8-dynamic"]
    L += [f"## {ev.title}", "", f"**Hypothesis (registered {ev.registered}).** {ev.hypothesis}", "",
          f"**Criterion.** {ev.criterion}", ""]
    if q:
        L += ["| run | val bpb fp32 | val bpb int8 | Δ bpb | decode tok/s fp32 | int8 | speed-up | weights MB fp32 → int8 "
              "| greedy agreement (64 tok) | verdict |", "|---|---|---|---|---|---|---|---|---|---|"]
        for rid, r in q.items():
            L.append(f"| `{rid}` | {r['fp32']['val_bpb']:.4f} | {r['int8']['val_bpb']:.4f} | {r['delta_val_bpb']:+.4f} | "
                     f"{r['fp32']['tokens_per_s']} | {r['int8']['tokens_per_s']} | {r['speedup_tokens_per_s']:.2f}x | "
                     f"{r['fp32']['weights_mb']} → {r['int8']['weights_mb']} | {r['greedy_token_agreement_64']:.2f} | "
                     f"**{r['verdict']}** |")
        r0 = next(iter(q.values()))
        L += ["", f"Commands: `morrowglass quant-int8 <run>`; commit `{r0['git']['commit'][:12]}`; engine "
                  f"{r0['quantized_engine']}; {r0['hardware']['chip']}, {r0['threads']} threads.", ""]
    else:
        L += ["Not measured yet.", ""]
    le_p = REPO_ROOT / "reports" / "lm_eval" / "summary.json"
    ev = EVALUATIONS["lm-eval-harness"]
    L += [f"## {ev.title}", "", f"**Hypothesis (registered {ev.registered}).** {ev.hypothesis}", "",
          f"**Criterion.** {ev.criterion}", ""]
    if le_p.exists():
        le = read_json(le_p)
        L += [f"Verdict: **{le['verdict']}**. Checks: " + ", ".join(f"`{k}` {v}" for k, v in le["checks"].items()) + ".",
              "", "| model | lambada_openai acc (± stderr) | lambada ppl | wikitext bits/byte | wikitext word ppl | "
              "our val split, harness bpb | own evaluator bpb | difference | docs | wall time |",
              "|---|---|---|---|---|---|---|---|---|---|"]
        for m, r in le["models"].items():
            own = f"{r['own_val_bpb']:.4f}" if "own_val_bpb" in r else "—"
            dif = f"{r['harness_minus_own_val_bpb']:+.4f}" if "harness_minus_own_val_bpb" in r else "—"
            ns = r["n_samples"]
            L.append(f"| `{m}` | {r['lambada_acc']:.4f} ± {r['lambada_acc_stderr'] or 0:.4f} | {r['lambada_perplexity']:.3g} | "
                     f"{r['wikitext_bits_per_byte']:.3f} | {r['wikitext_word_perplexity']:.4g} | "
                     f"{r['shakespeare_val_bits_per_byte']:.4f} | {own} | {dif} | "
                     f"{ns.get('lambada_openai')}/{ns.get('wikitext')}/{ns.get('morrowglass_shakespeare_val')} | "
                     f"{r['meta']['wall_time_s'] / 60:.0f} min |")
        any_r = next(iter(le["models"].values()), None)
        if any_r:
            L += ["", f"Harness: lm-eval {any_r['lm_eval_version']} (pinned in `eval/lm-eval-requirements.txt`). "
                      "Exact command per model: `reports/lm_eval/<model>/run_meta.json`; raw results: "
                      "`reports/lm_eval/<model>/**/results_*.json`; per-document lambada scores: "
                      "`lambada_per_doc.jsonl.gz`. Full per-sample logs stay in `artifacts/` (hashes in run_meta.json).", ""]
        if le["missing"]:
            L += [f"Missing: {', '.join(le['missing'])}.", ""]
    else:
        L += ["Not measured yet.", ""]
    hf = {p.parent.name: read_json(p) for p in sorted((REPO_ROOT / "reports" / "hf_export").glob("*/morrowglass.json"))}
    L += ["## Hugging Face Hub-compatible export (local only, not published)", ""]
    if hf:
        L += ["| run | model.safetensors bytes | sha256 | round-trip max abs logit diff | card |", "|---|---|---|---|---|"]
        for rid, h in hf.items():
            f = h["files"]["model.safetensors"]
            L.append(f"| `{rid}` | {f['bytes']:,} | `{f['sha256'][:16]}…` | {h['roundtrip_max_abs_logit_diff']} | "
                     f"[README.md](../reports/hf_export/{rid}/README.md) |")
        L += ["", "Publishing is an owner decision. After approval, the owner would run (per model):", "", "```bash",
              "uv run hf auth login        # the owner's own token; never stored in this repo",
              *[h["publish_command_after_owner_approval"] for h in hf.values()], "```", ""]
    else:
        L += ["Not exported yet.", ""]
    text = "\n".join(L)
    out.write_text(text)
    return str(out.relative_to(REPO_ROOT)) if out.is_relative_to(REPO_ROOT) else str(out)
